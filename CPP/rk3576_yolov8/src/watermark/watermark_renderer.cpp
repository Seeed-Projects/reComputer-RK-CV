WatermarkImage WatermarkRenderer::Render(std::uint64_t pts_ms) const {
  std::time_t seconds = static_cast<std::time_t>(pts_ms / 1000ULL);
  std::tm local_tm {};
  localtime_r(&seconds, &local_tm);

  std::ostringstream oss;
  oss << std::put_time(&local_tm, "%Y-%m-%d %H:%M:%S");
  return RenderText(oss.str());
}

WatermarkImage WatermarkRenderer::RenderText(const std::string& text, int x, int y) const {
  WatermarkImage image {};
  image.text = text;
  const int content_width =
      kPadding * 2 + static_cast<int>(text.size()) * (kGlyphWidth + kGlyphSpacing) - kGlyphSpacing;
  const int content_height = kPadding * 2 + kGlyphHeight;
  // NV12/RGA blend rectangles require even-aligned coordinates and sizes.
  image.width = AlignEven(content_width);
  image.height = AlignEven(content_height);
  image.x = AlignEven(x);
  image.y = AlignEven(y);
  image.rgba.assign(static_cast<std::size_t>(image.width) * image.height * 4, 0);

  for (int y = 0; y < image.height; ++y) {
    for (int x = 0; x < image.width; ++x) {
      SetPixel(image.rgba.data(), image.width, image.height, x, y, 0, 0, 0, 96);
    }
  }

  int cursor_x = kPadding;
  for (char c : text) {
    DrawGlyph(image.rgba.data(), image.width, image.height, cursor_x, kPadding,
              static_cast<char>(std::toupper(static_cast<unsigned char>(c))));
    cursor_x += kGlyphWidth + kGlyphSpacing;
  }

  return image;
}

void WatermarkRenderer::DrawGlyph(std::uint8_t* rgba, int image_width, int image_height, int x, int y, char c) const {
  const auto it = glyphs_.find(c);
  if (it == glyphs_.end()) {
    return;
  }
  const Glyph& glyph = it->second;
  for (int row = 0; row < kGlyphHeight; ++row) {
    for (int col = 0; col < kGlyphWidth; ++col) {
      const bool is_set = (glyph[static_cast<std::size_t>(row)] >> (kGlyphWidth - 1 - col)) & 0x01;
      if (is_set) {
        SetPixel(rgba, image_width, image_height, x + col, y + row, 255, 255, 255, 255);
      }
    }
  }
}

void WatermarkRenderer::SetPixel(std::uint8_t* rgba, int image_width, int image_height, int x, int y,
                                 std::uint8_t r, std::uint8_t g, std::uint8_t b, std::uint8_t a) const {
  if (x < 0 || y < 0 || x >= image_width || y >= image_height) {
    return;
  }
  const std::size_t index = static_cast<std::size_t>(y * image_width + x) * 4;
  rgba[index + 0] = r;
  rgba[index + 1] = g;
  rgba[index + 2] = b;
  rgba[index + 3] = a;
}

